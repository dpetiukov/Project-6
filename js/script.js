// 1. Гра «Вгадай число». Запропонуйте користувачеві загадати число від 0 до 100 і 
// відгадати його наступним способом: в кожній ітерації циклу поділяєте діапазон чисел 
// навпіл, записуєте результат в N і запитуєте у користувача 
// «Ваше число > N, < N або == N?». Залежно від відповіді користувача, зменшуєте діапазон. 
// Початковий діапазон від 0 до 100, поділяєте навпіл і отримуєте 50. Якщо користувач 
// вказав, що його число > 50, змінюєте діапазон числа від 51 до 100. І так доти, доки 
// користувач не вибере == N. Виведіть кількість спроб в консоль. 

let min = 0;
let max = 100;
let attempts = 0;
let guessed = false;

alert("Загадайте число від 0 до 100!");

while (!guessed) {
    let N = Math.floor((min + max) / 2);
    attempts++;

    let answer = prompt(
        `Ваше число > ${N}, < ${N} або == ${N}?`
    );

    if (answer === ">") {
        min = N + 1;
    } else if (answer === "<") {
        max = N - 1;
    } else if (answer === "==") {
        guessed = true;
        alert(`Я вгадав! Ваше число: ${N}`);
    } else {
        alert('Введіть тільки >, < або ==');
        attempts--;
    }

    if (min > max && !guessed) {
        alert("Ви десь помилилися у відповідях!");
        break;
    }
}

if (guessed) {
    console.log(`Кількість спроб: ${attempts}`);
}
